def main():
    assert len(MATERIALS) == 34, len(MATERIALS)
    assert len({m["slug"] for m in MATERIALS}) == 34
    out = Path(__file__).resolve().parents[1] / "data" / "registry" / "materials.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"materials": MATERIALS}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(MATERIALS)} materials)")


if __name__ == "__main__":
    main()
