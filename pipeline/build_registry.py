LB_PER_T = 2204.62262


def yahoo(symbol, label, unit, factor=1.0):
    return {"source": "yahoo", "symbol": symbol, "label": label, "unit": unit, "factor": factor}


def imf(code, label, unit="USD/t"):
    return {"source": "imf", "code": code, "label": label, "unit": unit}


def wb(column, label, unit):
    return {"source": "worldbank", "column": column, "label": label, "unit": unit}


def usgs_price(chapter, detail, label, element=None):
    d = {"chapter": chapter, "detail": detail, "label": label}
    if element:
        d["element"] = element
    return d


def prod(chapter, detail, label, commodity=None, reserves=None, comparable=True):
    return {
        "chapter": chapter,
        "commodity": commodity,
        "detail": detail,
        "label": label,
        "reserves_detail": reserves,
        "comparable": comparable,
    }


def cn(code, label, focus=False):
    d = {"code": code, "label": label}
    if focus:
        d["focus"] = True
    return d


